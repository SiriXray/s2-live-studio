function listPersonas() {
  return PERSONAS.map(persona => {
    const female = getVoice(persona.voices?.female) || getVoice(persona.voice);
    const male = getVoice(persona.voices?.male) || getVoice(persona.voice);
    return {
      id: persona.id, name: persona.name, gender: persona.gender, voice: persona.voice,
      voice_name: getVoice(persona.voice)?.name || '',
      voice_female: female?.id || '', voice_female_name: female?.name || '',
      voice_male: male?.id || '', voice_male_name: male?.name || '',
      look: persona.look, category: persona.category, wake_greeting: persona.wake_greeting, comment_style: persona.comment_style, gift_style: persona.gift_style, pk_style: persona.pk_style,
    };
  });
}

function getPersona(id) {
  return PERSONAS.find(persona => persona.id === id) || null;
}

