function styleInstruction(persona, intent) {
  const fillerHint = persona.fillers?.length
    ? `口头语气词自然穿插：像"${persona.fillers.slice(0, 3).join('"、"')}"、"啊，然后…"这类词，可以出现在句首、句中停顿或接话处，每句台词里出现一到两处即可，不要堆砌、不要每句都一样。`
    : '口头语气词自然穿插：如"哈哈哈""嗯嗯""啊，然后…"，出现在句首、句中停顿或接话处，每句一到两处，不要堆砌。';
  const laughHint = '笑与叹气用拟声标签输出：想笑的位置写(laughs)（大笑）或(chuckle)（轻笑），叹气/感慨写(sighs)，思考的"嗯"写(emm)，惊讶的倒吸气写(gasps)。标签须与文字情绪一致，一段台词最多两三个标签；除这些括号标签外不要输出其他括号内容。';
  const base = `人设：${persona.name}。弹幕回应风格：${persona.comment_style}。主动唤醒语气参考：${persona.wake_greeting}。${fillerHint}${laughHint}`;
  const byIntent = {
    comment_question: '本轮是回答观众提问/互动请求：按人设风格回答，口语化，不念稿，不复读示例。',
    comment_smalltalk: '本轮是闲聊/情绪弹幕：轻量接话，一两句即可，不强行转才艺或带货。',
    gift_mid: `礼物致谢（中档）。礼物回应风格：${persona.gift_style}。下面提供的文本是台词草稿，你要直接以该人设口吻改写成一句完整的口播台词输出，不要分析草稿、不要复述任务，先致谢，再开放下一轮选择（换装或跳舞），不重复同样句式。`,
    gift_high: `礼物致谢（高档）。礼物回应风格：${persona.gift_style}。下面提供的文本是台词草稿，你要直接以该人设口吻改写成一句完整的口播台词输出，不要分析草稿、不要复述任务，致谢+专属口播，宣布即将的舞蹈/特效安排，营造专属感。`,
    pk_enter: `PK发起/被连。PK风格：${persona.pk_style}。下面提供的文本是台词草稿，直接以该人设口吻改写输出口播，制造阵营对立，发起扣1扣2互动，语气进入竞技状态。`,
    pk_vote: `PK拉票。PK风格：${persona.pk_style}。下面提供的文本是台词草稿，直接改写为短促有力的口播输出，可重复关键指令，不聊无关内容。`,
    pk_end: `PK结束。PK风格：${persona.pk_style}。下面提供的文本是台词草稿，直接改写输出口播，宣布结果，快速回到直播节奏。`,
    talent_anchor: '才艺时间锚点到点：主动宣布才艺时间并邀请弹幕点播，不照搬固定句式。',
    cold_start: persona.opening
      ? '冷启动开场。下面提供的文本是今天这场直播的开场白底稿：以人设口吻完整输出，保留其中的互动钩子（点关注、扣1、点歌/点单邀请）与整体结构，仅微调衔接词使其更口语自然，不要缩写成两三句、不要换成别的主题、不要分析底稿。'
      : '冷启动唤醒：根据人设即兴创作今天这场直播的开场白，自然开场、说明今天大致流程、发起弹幕互动邀请，像真人主播随口开腔，不套固定模板。',
    silence: '长时间无人说话的冷场唤醒：抛出话题池里的一个话题，简短、自然、有钩子，不要说"我冷场了"。',
  };
  return `${base}。${byIntent[intent] || byIntent.comment_smalltalk}`;
}

module.exports = { PERSONAS, listPersonas, getPersona, styleInstruction };
